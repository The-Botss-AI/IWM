/**
 * One-shot database setup for the Docker stack (the `db-setup` service).
 * Does what `pnpm quickstart` does for the schema and demo data:
 *
 *   1. On a fresh database with no local migrations, writes an `init`
 *      migration from schema.prisma. packages/database/prisma is mounted from
 *      the host, so the migration lands in the same (gitignored) folder
 *      `pnpm quickstart` uses and both setups share one migration history.
 *   2. Applies migrations with `prisma migrate deploy` (never prompts, never
 *      resets).
 *   2b. When the schema is ahead of the database (an existing install after
 *      pulling a newer version), writes an `_upgrade` migration from
 *      `prisma migrate diff` and deploys it. Only purely additive changes are
 *      written: if the diff contains a DROP, RENAME, TRUNCATE or DELETE (for
 *      example SQL-only indexes you added in your own migrations), it stops
 *      and prints the SQL instead.
 *   3. Seeds the demo data while the database has no users, so a deleted
 *      demo admin is not brought back on the next start.
 *
 * Runs as root so it can write into the mounted folder; files it creates are
 * handed to the folder's owner.
 */
import { spawnSync } from 'node:child_process';
import { chownSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import prismaClient from '@prisma/client';

const DB_DIR = '/repo/packages/database';
const PRISMA_DIR = join(DB_DIR, 'prisma');
const MIGRATIONS_DIR = join(PRISMA_DIR, 'migrations');
const BIN = '/repo/node_modules/.bin';
// Same content `prisma migrate dev` writes.
const MIGRATION_LOCK = `# Please do not edit this file manually
# It should be added in your version-control system (i.e. Git)
provider = "postgresql"
`;

const childEnv = { ...process.env, CHECKPOINT_DISABLE: '1', PRISMA_HIDE_UPDATE_MESSAGE: '1' };

function fail(msg, ...hints) {
  console.error(`\n[db-setup] stopped: ${msg}`);
  for (const hint of hints) console.error(`  ${hint}`);
  process.exit(1);
}

function run(bin, args, { capture = false, env = childEnv } = {}) {
  const result = spawnSync(join(BIN, bin), args, {
    cwd: DB_DIR,
    env,
    stdio: capture ? ['ignore', 'pipe', 'inherit'] : 'inherit',
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0) fail(`\`${bin} ${args.join(' ')}\` failed (see the output above).`);
  return result.stdout ?? '';
}

function localMigrations() {
  if (!existsSync(MIGRATIONS_DIR)) return [];
  return readdirSync(MIGRATIONS_DIR).filter((entry) => /^\d/.test(entry));
}

/** Give a path we created to the owner of the mounted folder (the host user). */
function handToHostUser(path) {
  const { uid, gid } = statSync(PRISMA_DIR);
  try {
    chownSync(path, uid, gid);
  } catch {
    // Docker Desktop bind mounts map ownership themselves and may refuse chown.
  }
}

function writeMigration(name, sql) {
  // Prisma's own naming: UTC YYYYMMDDHHMMSS_name.
  const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  const dir = join(MIGRATIONS_DIR, `${stamp}_${name}`);
  const created = [];
  if (!existsSync(MIGRATIONS_DIR)) {
    mkdirSync(MIGRATIONS_DIR);
    created.push(MIGRATIONS_DIR);
  }
  mkdirSync(dir);
  writeFileSync(join(dir, 'migration.sql'), sql);
  created.push(dir, join(dir, 'migration.sql'));
  const lock = join(MIGRATIONS_DIR, 'migration_lock.toml');
  if (!existsSync(lock)) {
    writeFileSync(lock, MIGRATION_LOCK);
    created.push(lock);
  }
  created.forEach(handToHostUser);
  console.log(`[db-setup] wrote migration ${stamp}_${name}`);
}

function diffSql(from) {
  return run(
    'prisma',
    ['migrate', 'diff', ...from, '--to-schema-datamodel', 'prisma/schema.prisma', '--script'],
    { capture: true },
  );
}

/** Changes schema.prisma has that the database does not, as SQL ('' if none). */
function pendingSchemaSql() {
  const sql = diffSql(['--from-schema-datasource', 'prisma/schema.prisma']);
  const hasStatement = sql.split(/\r?\n/).some((l) => l.trim() && !l.trim().startsWith('--'));
  return hasStatement ? sql : '';
}

function writeInitMigration() {
  writeMigration('init', diffSql(['--from-empty']));
}

async function main() {
  const prisma = new prismaClient.PrismaClient();
  try {
    const [{ n: tables }] = await prisma.$queryRaw`
      SELECT count(*)::int AS n FROM information_schema.tables
      WHERE table_schema = current_schema()`;

    if (localMigrations().length === 0) {
      if (tables > 0) {
        fail(
          'the database already has tables, but packages/database/prisma/migrations is empty.',
          'Restore that folder from the clone that created the database, or start over with an',
          'empty database (this deletes all IWM data): docker compose --profile app down -v',
        );
      }
      writeInitMigration();
    }

    run('prisma', ['migrate', 'deploy']);

    const pending = pendingSchemaSql();
    if (pending) {
      if (/\b(DROP|RENAME|TRUNCATE|DELETE)\b/i.test(pending)) {
        fail(
          'schema.prisma differs from the database in a way that would drop, rename or delete something.',
          'Nothing was changed. Review the SQL below and create the migration yourself',
          '(see "Upgrading an existing install" in the README):',
          '',
          pending,
        );
      }
      writeMigration('upgrade', pending);
      run('prisma', ['migrate', 'deploy']);
    }
    console.log('[db-setup] schema is up to date');

    if ((await prisma.user.count()) > 0) {
      console.log('[db-setup] database already has users, demo seed skipped');
      return;
    }
    run('tsx', ['prisma/seed.ts'], {
      env: { ...childEnv, NODE_ENV: 'development', ALLOW_SEED: 'true' },
    });
    console.log('[db-setup] demo data ready (admin@example.com / demo-admin-password)');
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((err) => fail(err instanceof Error ? err.message : String(err)));
